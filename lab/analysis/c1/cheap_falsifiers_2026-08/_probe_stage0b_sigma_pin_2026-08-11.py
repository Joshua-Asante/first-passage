"""Q-MCLTAS-1 Stage 0b -- sigma-pin, converting the Wall-B falsifier to cohort-bound
delta/sigma units.

$0 / K=0 / NO DATA PULL. Every sigma below is READ from the committed, measured MCL
sigma surface in lab/analysis/c1/tradeify_fade_stage0_2026-07-30/RESULTS_sigma_native.md
(generated by stage2_sigma.windowed_sigma on the wed_thu ex-FOMC cohort). Nothing is
re-measured here; this script does arithmetic on published cells only.

The 2026-08-11 scoping brief assumed Stage 0b would read "the already-committed 2023
cache". THAT CACHE IS NOT ON DISK (fade stage0 dir holds RESULTS markdown only; heavy
artifacts gitignored and absent). The committed sigma SURFACE substitutes, and is
strictly better: it is a measured result, not a re-derivation.
"""

import math

# --- Frozen from the probe falsifier (see _cheap_falsifier_mcl_tas_probe_2026-08-11.py)
REQUIRED_DELTA_USD = 11.60   # 4.0 x RT $2.90; per contract, per event

# --- Measured MCL sigma surface, wed_thu ex-FOMC (RESULTS_sigma_native.md, PRIMARY table)
#     15-minute column only -- the shortest measured duration.
SIGMA_15MIN_USD = {
    "09:30": 28.35, "10:00": 26.95, "10:30": 39.19, "11:00": 30.42,
    "12:00": 25.22, "13:00": 20.79, "14:00": 23.46, "15:00":  9.15,
}
WINDOW_MINUTES = 2.0          # CME CL settlement window 14:28-14:30 ET
SOURCE_MINUTES = 15.0

# Published-vs-this-run panel discrepancy, RESULTS_sigma_native.md ("DOES NOT REPRODUCE"):
# config-legal cell 120min@09:30 published $101.16 vs this run $77.67.
PANEL_INFLATION = 101.16 / 77.67

# --- Estate's COMMITTED causal-public delta/sigma record.
#     Only D5 carries a documented delta/sigma in this estate (strategy_harvest.md section 4).
D5_CONSERVATIVE = 0.113       # t-scaled, the reading actually used
D5_OPTIMISTIC   = 0.194       # R^2-derived, explicitly rejected as too generous

def scale(sig15, minutes=WINDOW_MINUTES):
    """sqrt-time scaling. Assumes iid increments; see caveat in the log."""
    return sig15 * math.sqrt(minutes / SOURCE_MINUTES)

print("=" * 78)
print("Q-MCLTAS-1 Stage 0b -- sigma-pin (committed surface; $0, K=0, no pull)")
print("=" * 78)

print(f"\nRequired delta (Wall B)             : ${REQUIRED_DELTA_USD:.2f}/contract/event")
print(f"Settlement window                   : {WINDOW_MINUTES:.0f} min (14:28-14:30 ET)")
print(f"Source cells                        : measured 15-min sigma, wed_thu ex-FOMC")

print(f"\n--- 2-minute sigma implied by each measured 15-min cell (sqrt-time) ---")
for start, s15 in SIGMA_15MIN_USD.items():
    print(f"  {start}  sigma_15m = ${s15:6.2f}  ->  sigma_2m = ${scale(s15):5.2f}")

nearest   = scale(SIGMA_15MIN_USD["14:00"])   # 14:00-14:15, adjacent to the window
generous  = scale(max(SIGMA_15MIN_USD.values()))  # busiest cell anywhere in the day
gen_panel = generous * PANEL_INFLATION            # + the published-panel inflation

print(f"\n--- Three sigma readings, increasingly generous to the candidate ---")
print(f"  (a) nearest-in-time (14:00 cell, adjacent to window) : ${nearest:5.2f}")
print(f"  (b) most generous cell in the whole surface (10:30)  : ${generous:5.2f}")
print(f"  (c) (b) + published-panel inflation ({PANEL_INFLATION:.2f}x)        : ${gen_panel:5.2f}")
print(f"      [(c) stacks every generosity available; it is not a defensible estimate,")
print(f"       it is the ceiling the kill has to survive.]")

print(f"\n--- Required delta/sigma, vs the estate's only COMMITTED delta/sigma ---")
print(f"{'sigma reading':<46} {'req d/s':>9} {'vs D5 opt':>11} {'vs D5 cons':>12}")
print("-" * 78)
rows = [("(a) nearest-in-time  $%.2f" % nearest,   nearest),
        ("(b) most generous cell  $%.2f" % generous, generous),
        ("(c) + published-panel inflation  $%.2f" % gen_panel, gen_panel)]
worst_case_ratio = None
for label, sig in rows:
    req = REQUIRED_DELTA_USD / sig
    r_opt, r_con = req / D5_OPTIMISTIC, req / D5_CONSERVATIVE
    if worst_case_ratio is None or r_opt < worst_case_ratio:
        worst_case_ratio = r_opt
    print(f"{label:<46} {req:>9.3f} {r_opt:>10.1f}x {r_con:>11.1f}x")
print("-" * 78)
print(f"D5 committed delta/sigma: conservative {D5_CONSERVATIVE} (used) / "
      f"optimistic {D5_OPTIMISTIC} (rejected as too generous)")

print(f"\n--- Verdict ---")
print(f"  Smallest gap available anywhere in this table: {worst_case_ratio:.1f}x")
print(f"  (most generous sigma stacking x the delta/sigma the estate itself REJECTED")
print(f"   as too optimistic -- i.e. the friendliest number that can be constructed)")
print(f"\n  => Wall B holds. The delta/sigma conversion does NOT rescue the candidate;")
print(f"     it makes the gap WORSE than the bp-space comparison implied (4.63x).")
print(f"\n  CORRECTION to the 2026-08-11 scoping brief: it estimated the cohort-bound gap")
print(f"  would narrow to ~2.4x. That rested on a GC fix-window sigma I invented rather")
print(f"  than measured. Against the estate's only COMMITTED delta/sigma the floor is")
print(f"  {worst_case_ratio:.1f}x. lesson_metric_cohort_provenance_binding, second firing, same probe.")
print("=" * 78)
